"""Build the fast UI font from the project's PingFangUI-VF source font.

Requires: pip install fonttools brotli
The complete common-character web font remains in public/assets/fonts for
user-entered characters outside the fast UI subset.
"""

from pathlib import Path
from fontTools import subset
from fontTools.ttLib import TTFont


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "assets/fonts/PingFangUI-SC.ttf"
COMPRESSED_PARTS = [ROOT / "assets/fonts/PingFangUI-SC.ttf.br.001", ROOT / "assets/fonts/PingFangUI-SC.ttf.br.002"]
CORE = ROOT / "public/assets/fonts/PingFangUI-SC-core.woff2"
CSS = ROOT / "src/styles/font-faces.css"

# Keep all characters present in the app source, plus frequent chat characters.
source_text = "".join(
    path.read_text(encoding="utf-8")
    for folder in (ROOT / "src",)
    for path in folder.rglob("*.ts*")
) + (ROOT / "index.html").read_text(encoding="utf-8")
common_chat = (
    "的一是不了在人有我他这中大来上国个到说们为子和你地出道也时年得就那要下以生会自着去之过家学对可她里后小心多天而能好都然没日于起还发成事只作当想看文无开手十用主行方同些知如前所本见经头面公果明间点月高情关现新力比将定电机话谁什怎吗呢吧哦啊呀嗯哈哈谢请您老师孩子身体舒服感谢理解今天明天晚上上午下午消息聊天微信红包转账文件照片视频语音电话时间分钟秒已经收到发送您好再见喜欢朋友"
)
font = TTFont(SOURCE) if SOURCE.exists() else TTFont(BytesIO(brotli.decompress(b"".join(part.read_bytes() for part in COMPRESSED_PARTS))))
available = set(font.getBestCmap())
core_codes = ({ord(char) for char in source_text + common_chat} | set(range(32, 127))) & available
extra_codes = available - core_codes

options = subset.Options()
options.flavor = "woff2"
subsetter = subset.Subsetter(options=options)
subsetter.populate(unicodes=core_codes)
subsetter.subset(font)
font.flavor = "woff2"
font.save(CORE)


def ranges(codes):
    ordered = sorted(codes)
    spans = []
    start = end = ordered[0]
    for code in ordered[1:]:
        if code == end + 1:
            end = code
        else:
            spans.append((start, end))
            start = end = code
    spans.append((start, end))
    return ", ".join(
        f"U+{a:X}" if a == b else f"U+{a:X}-{b:X}" for a, b in spans
    )


CSS.write_text(
    """/* Generated by scripts/build-font-subsets.py from ACT-02/PingFangUI-VF. */
@font-face {
  font-family: "PingFang UI SC";
  src: url("/assets/fonts/PingFangUI-SC-core.woff2") format("woff2");
  font-style: normal;
  font-weight: 100 900;
  font-display: swap;
  unicode-range: """
    + ranges(core_codes)
    + ";\n}\n"
    + """@font-face {
  font-family: "PingFang UI SC";
  src: url("/assets/fonts/PingFangUI-SC.woff2") format("woff2");
  font-style: normal;
  font-weight: 100 900;
  font-display: swap;
  unicode-range: """
    + ranges(extra_codes)
    + ";\n}\n",
    encoding="utf-8",
)
print(f"Core: {len(core_codes)} characters, {CORE.stat().st_size} bytes")
print(f"Extended: {len(extra_codes)} characters")
